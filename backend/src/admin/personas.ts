/**
 * The console's persona view (D-AI-12, phase A6).
 *
 * ---------------------------------------------------------------------------
 * THIS IS THE ONE PLACE PERSONA CONVERSATIONS BECOME READABLE
 * ---------------------------------------------------------------------------
 * `guard.ts` decides what a persona says. The metrics say how often and how
 * much. Neither carries a word of it, because rule 1 names Prometheus labels
 * *and values*, so the live persona feed everybody asks for cannot exist.
 *
 * What a persona actually said is read here, through the console, and every
 * read is audited exactly as a reported conversation is.
 *
 * ---------------------------------------------------------------------------
 * WHAT IS DIFFERENT FROM `review.ts`, AND WHAT IS NOT
 * ---------------------------------------------------------------------------
 * Different: no report is required. An ordinary conversation is opened only
 * when somebody reports it — there is no browsing and no search. A persona
 * conversation may be opened at any time, because the operator reads them for
 * tone and quality and said so (D-AI-12).
 *
 * Not different: the audit. In fact it matters *more* here. With no report
 * gating access, **the audit log stops being a record and becomes the only
 * remaining control** on reading a stranger's messages. So the D33 guarantee is
 * unchanged and non-negotiable — the audit row is written first, in the same
 * transaction, and a failure to write it fails the read.
 *
 * One side of the conversation belongs to the operator. The other side does
 * not, and both ride in one transcript. That asymmetry is the entire reason
 * this file looks like `review.ts` rather than like a debug endpoint.
 */

import type { Config } from '../config';
import type { Database } from '../storage/pool';
import type { Profile } from '../protocol/types';
import { newAuditId } from '../util/ids';
import type { AdminIdentity } from './auth';

export interface PersonaConversationSummary {
  readonly conversationId: string;
  readonly personaId: string;
  /** The identity the stranger saw. Generated by us, so not user content. */
  readonly surface: Profile | null;
  readonly startedAt: Date;
  readonly endedAt: Date | null;
  readonly replies: number;
  readonly costMicroCents: number;
  readonly limitsTripped: readonly string[];
  readonly flagged: boolean;
}

export interface PersonaTranscriptLine {
  readonly messageId: string;
  /** True when the persona sent it. The operator's own words. */
  readonly fromPersona: boolean;
  readonly at: Date;
  readonly body: string;
  readonly moderationAction: string | null;
}

export interface PersonaConversationDetail extends PersonaConversationSummary {
  readonly messages: readonly PersonaTranscriptLine[];
  /** Null when the retention worker has already removed the transcript. */
  readonly conversationPresent: boolean;
}

/** What the console shows beside the kill switch. */
export interface PersonaOverview {
  readonly spentMicroCents: number;
  readonly limitMicroCents: number;
  readonly exhaustedAt: Date | null;
  readonly conversationsToday: number;
  readonly flaggedOpen: number;
}

export class PersonaConsoleService {
  constructor(
    private readonly db: Database,
    private readonly config: Config,
  ) {}

  /**
   * The list. Flagged first, then most recent.
   *
   * **No audit row**, deliberately, and the reasoning is `review.ts`'s: nothing
   * returned here is user content. It is persona ids, our own generated
   * surfaces, counts and costs. Auditing a list that is rendered on every visit
   * to the console would bury the reads that matter in noise, which makes the
   * audit trail worse rather than better.
   */
  async list(limit = 50, flaggedOnly = false): Promise<readonly PersonaConversationSummary[]> {
    const { rows } = await this.db.query<PersonaRow>(
      `select conversation_id, persona_id, surface, started_at, ended_at,
              replies, cost_micro_cents, limits_tripped, flagged
         from persona_conversations
        where ($2::boolean is false or flagged is true)
        order by flagged desc, started_at desc
        limit $1`,
      [Math.min(Math.max(limit, 1), 200), flaggedOnly],
    );
    return rows.map(toSummary);
  }

  /**
   * One conversation, with its transcript.
   *
   * The audit row is written **before** a single message body is selected, in
   * the same transaction. If the insert fails the transaction rolls back and
   * the caller gets an error rather than content: the guarantee is not "we
   * usually log reads", it is "a read that was not logged did not happen"
   * (D33).
   *
   * Returns null when there is no such persona conversation. A conversation
   * whose transcript has already expired is **not** null — it comes back with
   * `conversationPresent: false`, because "this existed and has been deleted on
   * schedule" is a different fact from "this never existed", and the retention
   * promise is easier to believe when the console can show the difference.
   */
  async open(
    conversationId: string,
    justification: string,
    identity: AdminIdentity,
    nowMs = Date.now(),
  ): Promise<PersonaConversationDetail | null> {
    return this.db.transaction(async (client) => {
      const indexResult = await client.query<PersonaRow>(
        `select conversation_id, persona_id, surface, started_at, ended_at,
                replies, cost_micro_cents, limits_tripped, flagged,
                persona_session_id
           from persona_conversations
          where conversation_id = $1`,
        [conversationId],
      );
      const row = indexResult.rows[0];
      if (row === undefined) return null;

      // Before any body is selected. The ordering is the whole control: an
      // audit row written afterwards would be missing for exactly the reads
      // that failed halfway, which are the ones worth knowing about.
      await client.query(
        `insert into admin_audit
           (audit_id, actor, role, action, subject_type, subject_id, case_id,
            justification, created_at, retention_expires_at)
         values ($1, $2, $3, 'viewed_persona_conversation', 'conversation', $4,
                 null, $5, $6, $7)`,
        [
          newAuditId(),
          identity.accountId,
          identity.role,
          conversationId,
          justification,
          new Date(nowMs),
          // Stamped at insert like every other deadline (D17).
          new Date(nowMs + this.config.retention.days.adminAudit * 24 * 60 * 60 * 1000),
        ],
      );

      const messagesResult = await client.query<{
        message_id: string;
        sender_session_id: string;
        server_timestamp: Date;
        body: string;
        moderation_action: string | null;
      }>(
        `select m.message_id, m.sender_session_id, m.server_timestamp, m.body,
                m.moderation_action
           from messages m
          where m.conversation_id = $1
          order by m.server_timestamp asc`,
        [conversationId],
      );

      const conversationResult = await client.query<{ session_a: string }>(
        'select session_a from conversations where conversation_id = $1',
        [conversationId],
      );
      const conversationPresent = conversationResult.rows.length > 0;

      const personaSessionId = row.persona_session_id;

      const messages: PersonaTranscriptLine[] = messagesResult.rows.map((m) => ({
        messageId: m.message_id,
        fromPersona: personaSessionId !== null && m.sender_session_id === personaSessionId,
        at: m.server_timestamp,
        body: m.body,
        moderationAction: m.moderation_action,
      }));

      return { ...toSummary(row), messages, conversationPresent };
    });
  }

  /** The numbers that sit next to the kill switch. */
  async overview(): Promise<PersonaOverview> {
    const spend = await this.db.query<{
      spent_micro_cents: string;
      limit_micro_cents: string;
      exhausted_at: Date | null;
    }>(
      `select spent_micro_cents, limit_micro_cents, exhausted_at
         from persona_spend
        where period = date_trunc('month', now())::date`,
    );

    const counts = await this.db.query<{ today: string; flagged: string }>(
      `select count(*) filter (where started_at > now() - interval '1 day')::text as today,
              count(*) filter (where flagged)::text as flagged
         from persona_conversations`,
    );

    const s = spend.rows[0];
    const c = counts.rows[0];

    return {
      spentMicroCents: Number(s?.spent_micro_cents ?? 0),
      limitMicroCents: Number(s?.limit_micro_cents ?? 0),
      exhaustedAt: s?.exhausted_at ?? null,
      conversationsToday: Number(c?.today ?? 0),
      flaggedOpen: Number(c?.flagged ?? 0),
    };
  }
}

interface PersonaRow extends Record<string, unknown> {
  conversation_id: string;
  persona_id: string;
  surface: Profile | null;
  started_at: Date;
  ended_at: Date | null;
  replies: number;
  cost_micro_cents: string;
  limits_tripped: string[];
  flagged: boolean;
  persona_session_id?: string | null;
}

function toSummary(row: PersonaRow): PersonaConversationSummary {
  return {
    conversationId: row.conversation_id,
    personaId: row.persona_id,
    surface: row.surface,
    startedAt: row.started_at,
    endedAt: row.ended_at,
    replies: row.replies,
    costMicroCents: Number(row.cost_micro_cents),
    limitsTripped: row.limits_tripped,
    flagged: row.flagged,
  };
}
