/**
 * Starts tracing before anything else in the process exists.
 *
 * Loaded with `node --require ./dist/tracing/preload.js`, which is the only
 * arrangement that works and the reason it is a separate file.
 *
 * ---------------------------------------------------------------------------
 * WHY A PRELOAD, AFTER TRYING NOT TO USE ONE
 * ---------------------------------------------------------------------------
 * The first version of this called `startTracing` from `index.ts`, after
 * `loadConfig`, on the reasoning that a process with tracing off should never
 * load the SDK at all. That reasoning was right and the implementation did not
 * work: `registerInstrumentations` patches a module by replacing its exports,
 * and by the time an async `main()` runs, `pg` and `ioredis` have already been
 * imported at the top of `index.ts` and every module it pulls in.
 *
 * The comment written at the time said the cost was "a small number of early
 * spans". It was not. **Nothing was patched and no span was ever produced** —
 * Tempo received zero traces from a stack that reported no errors, was
 * reachable, and accepted OTLP when poked by hand. A tracing pipeline that
 * exports nothing looks exactly like a quiet system.
 *
 * ---------------------------------------------------------------------------
 * AND HOW THE ORIGINAL PROPERTY IS KEPT ANYWAY
 * ---------------------------------------------------------------------------
 * The flag is read here, from the raw environment, **before** anything
 * OpenTelemetry is required. With `TRACING_ENABLED` unset or false this file
 * does nothing at all and the SDK never enters the address space — which was
 * the point of not using a preload in the first place, obtained by ordering
 * rather than by placement.
 *
 * That is also why the `require` below is not a top-level `import`: an import
 * is hoisted and would load the SDK unconditionally, which is the exact
 * behaviour this file exists to avoid.
 */

/* eslint-disable @typescript-eslint/no-var-requires */

function truthy(value: string | undefined): boolean {
  return value === 'true' || value === '1' || value === 'yes';
}

if (truthy(process.env.TRACING_ENABLED)) {
  // Required, not imported, so nothing above loads when tracing is off.
  const { startTracing } = require('./index') as typeof import('./index');

  const tracing = startTracing({
    endpoint: process.env.TRACING_ENDPOINT ?? 'http://tempo:4318',
    serviceName: process.env.TRACING_SERVICE_NAME ?? 'karobakbak-backend',
    // The application's own id is generated by `loadConfig`, which has not run
    // yet, so the preload uses whatever the environment supplies and falls back
    // to the hostname — which in a container is the container id and is stable
    // for the life of the process.
    instanceId: process.env.INSTANCE_ID ?? process.env.HOSTNAME ?? 'unknown',
    /*
      Never true in a running process, whatever the environment.

      This was `!isProduction`, copying the logger's rule, and the load stack
      went into a restart loop on its first database query: `onEnd` runs inside
      the instrumented call, so the throw failed the query it was observing. A
      safety control that takes the service down is an outage with good
      intentions. It redacts and reports instead; `tracing.test.ts` is the only
      thing that asserts the refusal, and it does so directly.
    */
    strict: false,
    /*
      One JSON object per line on stderr, matching `logger.ts`'s shape so the
      log shipper parses it with the same pipeline.

      Deliberately not the real logger: that needs `Config`, which needs
      `loadConfig`, which has not run. Building it here would drag the whole
      configuration module into the preload and defeat the ordering above. The
      fields written are constants and an attribute *name* — never a value, for
      the reason the scrubber itself gives.
    */
    report: (level, message, fields) => {
      process.stderr.write(
        `${JSON.stringify({
          ts: new Date().toISOString(),
          level,
          msg: message,
          component: 'tracing',
          ...fields,
        })}\n`,
      );
    },
  });

  // The process exits through `index.ts`'s signal handlers, which cannot see
  // this handle. Flushing on exit is the backstop, and it is best-effort: a
  // collector that is unreachable must never delay or fail a shutdown.
  process.on('beforeExit', () => {
    void tracing.shutdown();
  });
}
